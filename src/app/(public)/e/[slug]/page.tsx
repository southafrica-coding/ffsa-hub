type EventBrand =
  | "ff"
  | "the_send"
  | "ffsa_camps"
  | "preachers"
  | "wild_ones"
  | "missio";

// Bespoke landing pages keyed by the event's brand flag (migration 077 +
// the ffsa_camps follow-up). THE SEND, FFSA Camps and PREACHERS each get
// their own bespoke storefront; the FFSA house brand ('ff', also the
// default) renders the FfsaStorefront built against the FFSA Brand Deck.
// All are intentionally event-bespoke and own the full viewport. An
// explicit brand always wins; the legacy slug/title heuristic only runs
// for unmigrated rows (brand null/empty) so they still route correctly
// until every event row has its brand set.
function resolveEventBrand(event: {
  brand?: string | null;
  public_slug?: string | null;
  title?: string | null;
}): EventBrand {
  if (event.brand === "the_send") return "the_send";
  if (event.brand === "ffsa_camps") return "ffsa_camps";
  if (event.brand === "preachers") return "preachers";
  if (event.brand === "wild_ones") return "wild_ones";
  if (event.brand === "missio") return "missio";
  if (event.brand) return "ff";
  const slug = (event.public_slug ?? "").toLowerCase();
  const title = (event.title ?? "").toLowerCase();
  if (slug.includes("the-send") || title.includes("the send")) return "the_send";
  if (slug.includes("ffsa-camps") || slug.includes("camps") || title.includes("camps"))
    return "ffsa_camps";
  if (slug.includes("preachers") || title.includes("preachers")) return "preachers";
  if (slug.includes("wild-ones") || slug.includes("wild ones") || title.includes("wild ones"))
    return "wild_ones";
  if (slug.includes("missio") || title.includes("missio")) return "missio";
  return "ff";
}

export const dynamic = "force-dynamic";

// Per-event link preview: title + description come from the event, while the
// share image is generated by the sibling opengraph-image route (Next wires
// og:image + twitter:image automatically).
export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string }>;
}): Promise<Metadata> {
  const { slug } = await params;
  const supabase = createAdminClient();
  const { data: event } = await getEventBySlug(supabase, slug);

  if (!event || !event.ticketing_enabled || event.status !== "published") {
    return { title: "Event not available" };
  }

  const dateLine = [
    formatEventDateRange(event.start_date, event.end_date),
    event.location,
  ]
    .filter(Boolean)
    .join(" · ");
  const description =
    eventDescriptionToPlainText(event.description).slice(0, 200) ||
    dateLine ||
    event.title;

  return {
    title: event.title,
    description,
    openGraph: {
      title: event.title,
      description,
      type: "website",
    },
    twitter: {
      card: "summary_large_image",
      title: event.title,
      description,
    },
  };
}

export default async function PublicEventPage({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const supabase = createAdminClient();

  const { data: event } = await getEventBySlug(supabase, slug);

  // A cancelled event that ticket holders may be revisiting: show the
  // organiser's cancellation note rather than the generic notice, so
  // people who bought tickets understand what happened.
  if (event?.status === "cancelled") {
    return (
      <PublicFormNotice
        eyebrow="Event cancelled"
        heading={`${event.title} has been cancelled`}
        body={
          event.cancellation_message?.trim() ||
          "This event is no longer going ahead. If you bought a ticket, you'll be refunded to the card or account you paid from."
        }
      />
    );
  }

  if (
    !event ||
    !event.ticketing_enabled ||
    event.status !== "published"
  ) {
    return (
      <PublicFormNotice
        eyebrow="Event"
        heading="Event not available"
        body="This event may have ended, been moved, or the link is incorrect."
      />
    );
  }

  const { data: ticketTypes } = await listTicketTypesByEvent(
    supabase,
    event.id,
    { onlyActive: true }
  );

  const eventProps = {
    id: event.id,
    title: event.title,
    // Sanitised once here so every storefront receives safe rich HTML,
    // covering both the edit API and the direct-supabase create paths.
    description: sanitizeEventDescription(event.description),
    location: event.location,
    start_date: event.start_date,
    end_date: event.end_date,
    start_time: event.start_time,
    end_time: event.end_time,
    logo_url: event.logo_url ?? null,
    // Drives price formatting and which pay buttons render — PayFast
    // is ZAR-only, so a non-ZAR event is Stripe-only.
    currency: event.currency ?? "ZAR",
    // The F&F storefront's seat counter reads this; the five bespoke
    // brands ignore the extra key.
    max_capacity: event.max_capacity ?? null,
  };

  const brand = resolveEventBrand(event);
  const checkoutQuestions =
    (event.checkout_questions as FormField[] | null) ?? [];
  // Resolve once here (email forced on+required, hidden fields never
  // required) so every storefront gets a complete, safe config.
  const buyerFields = resolveBuyerFields(event.buyer_fields);

  if (brand === "the_send") {
    return (
      <TheSendStorefront
        event={eventProps}
        ticketTypes={ticketTypes ?? []}
        checkoutQuestions={checkoutQuestions}
        buyerFields={buyerFields}
      />
    );
  }
  if (brand === "ffsa_camps") {
    return (
      <CampsStorefront
        event={eventProps}
        ticketTypes={ticketTypes ?? []}
        checkoutQuestions={checkoutQuestions}
        buyerFields={buyerFields}
      />
    );
  }
  if (brand === "preachers") {
    return (
      <PreachersStorefront
        event={eventProps}
        ticketTypes={ticketTypes ?? []}
        checkoutQuestions={checkoutQuestions}
        buyerFields={buyerFields}
      />
    );
  }
  if (brand === "wild_ones") {
    return (
      <WildOnesStorefront
        event={eventProps}
        ticketTypes={ticketTypes ?? []}
        checkoutQuestions={checkoutQuestions}
        buyerFields={buyerFields}
      />
    );
  }
  if (brand === "missio") {
    return (
      <MissioStorefront
        event={eventProps}
        ticketTypes={ticketTypes ?? []}
        checkoutQuestions={checkoutQuestions}
        buyerFields={buyerFields}
      />
    );
  }

  // brand === "ff" — the FFSA house brand, and the default. The generic
  // F&F public event page, recomposed onto the Hub's editorial design
  // system (docs/redesign frame 4c). It reads the same brand module as the
  // FFSA emails, so the buyer's whole journey is one identity.
  //
  // heroImageUrl is deliberately not passed: 4c wants a full-bleed photo
  // masthead, but `events` has no hero-photo column (logo_url is a brand
  // mark, not a cover). The masthead renders on its black ground until a
  // column exists, at which point this is a one-line change.
  return (
    <FfsaStorefront
      event={eventProps}
      ticketTypes={ticketTypes ?? []}
      checkoutQuestions={checkoutQuestions}
      buyerFields={buyerFields}
    />
  );
}
