-- ============================================================
-- FFSA Hub — Migration 173: needs_decision on the billing schedule
-- Billing, STEP 9b (the queue's half of it).
-- See docs/redesign/07-finance-billing.md §4
-- ============================================================
-- The schedule builder now marks charges whose generation window closed before
-- the student was accepted. The status CHECK from migration 095 does not allow
-- that value, so those rows could not be stored at all — and the API was
-- quietly writing every row as 'scheduled' regardless, which would have let a
-- late acceptance generate an invoice dated in the past. Exactly what §4 says
-- must never happen.
--
-- 'needs_decision' is a HOLD, not an error state:
--   · the charge is real and she owes it
--   · its dates are untouched
--   · nothing generates it until a person chooses one of three outcomes
--     (catch up as one invoice dated today / issue each separately dated
--      today / start her schedule from now)
--
-- Resolution never backdates. Both "issue" outcomes move the generation date
-- to today; "start from now" cancels the row and keeps it in history.
-- ============================================================

ALTER TABLE public.student_billing_schedule
  DROP CONSTRAINT IF EXISTS student_billing_schedule_status_check;

ALTER TABLE public.student_billing_schedule
  ADD CONSTRAINT student_billing_schedule_status_check
  CHECK (status IN (
    'scheduled',       -- planned, generation date still ahead
    'needs_decision',  -- generation window closed before acceptance — held
    'generated',       -- invoice exists in Xero
    'sent',            -- emailed to the student
    'paid',
    'cancelled'        -- dropped; kept for history, never deleted
  ));

-- Who resolved a hold, how, and when. Nullable — an ordinary scheduled row has
-- never been held, and most rows never will be.
ALTER TABLE public.student_billing_schedule
  ADD COLUMN IF NOT EXISTS decision_outcome text
    CHECK (decision_outcome IS NULL OR decision_outcome IN (
      'catch_up_single', 'issue_separately', 'start_from_now'
    )),
  ADD COLUMN IF NOT EXISTS decided_by uuid REFERENCES public.users(id),
  ADD COLUMN IF NOT EXISTS decided_at timestamptz;

COMMENT ON COLUMN public.student_billing_schedule.status IS
  'needs_decision = its generation window closed before the student was accepted. Real, owed, dates intact, and generated by nobody until a person decides. Never auto-resolve it.';
COMMENT ON COLUMN public.student_billing_schedule.decision_outcome IS
  'How a held charge was resolved. Kept so the record shows a person chose, not that the system guessed.';

-- The queue is "everything still held", read per student and across a school.
CREATE INDEX IF NOT EXISTS idx_sbs_needs_decision
  ON public.student_billing_schedule (plan_id)
  WHERE status = 'needs_decision';

-- ------------------------------------------------------------
-- A held charge must never be generated by an automated path. The columns
-- alone rely on every future caller remembering; this does not.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.block_generating_held_charge()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF OLD.status = 'needs_decision'
     AND NEW.status IN ('generated', 'sent')
     AND NEW.decision_outcome IS NULL THEN
    RAISE EXCEPTION
      'This charge is held for a decision. Resolve it (catch up / issue separately / start from now) before generating an invoice.';
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_block_generating_held_charge ON public.student_billing_schedule;
CREATE TRIGGER trg_block_generating_held_charge
  BEFORE UPDATE ON public.student_billing_schedule
  FOR EACH ROW EXECUTE FUNCTION public.block_generating_held_charge();

