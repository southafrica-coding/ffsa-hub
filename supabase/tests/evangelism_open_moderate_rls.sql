SELECT CASE WHEN ok THEN 'PASS' ELSE 'FAIL' END AS result, name, detail
FROM public.ev_open_moderate_results
ORDER BY n;

DO $$
DECLARE
  n_pass int;
  n_fail int;
BEGIN
  SELECT count(*) FILTER (WHERE ok), count(*) FILTER (WHERE NOT ok)
    INTO n_pass, n_fail
  FROM public.ev_open_moderate_results;
  RAISE NOTICE 'evangelism_open_moderate_rls: % passed, % failed', n_pass, n_fail;
  IF n_fail > 0 THEN
    RAISE EXCEPTION '% checks failed', n_fail;
  END IF;
END $$;

